def _check_environment() -> bool:
    """Basic runtime environment checks."""
    # Check we're not being debugged via common Python debuggers
    frame = sys._getframe(0)
    suspicious_modules = {'pydevd', 'debugpy', 'pdb', '_pydevd_bundle'}
    loaded = set(sys.modules.keys())
    if suspicious_modules & loaded:
        return False
    return True


# ────────────────────────────────────────────────
#  Public API — Keys assembled on demand
