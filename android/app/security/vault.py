def _xor_bytes(a: bytes, b: bytes) -> bytes:
    """XOR two byte strings of equal length."""
    return bytes(x ^ y for x, y in zip(a, b))


def _assemble(fragment_id: int) -> bytes:
    """Assemble a key from its XOR-split fragments with integrity check."""
    entry = _FT.get(fragment_id)
    if entry is None:
        raise RuntimeError("Vault integrity error: missing fragment")

    part_b85, mask_b85, checksum = entry

    try:
        part = base64.b85decode(part_b85)
        mask = base64.b85decode(mask_b85)
    except Exception:
        raise RuntimeError("Vault integrity error: corrupt fragment data")

    if len(part) != len(mask):
        raise RuntimeError("Vault integrity error: fragment size mismatch")

    key = _xor_bytes(part, mask)

    # Verify SHA-256 checksum prefix to detect tampering
    digest = hashlib.sha256(key).hexdigest()
    if not digest.startswith(checksum):
        raise RuntimeError("Vault integrity error: checksum verification failed")

    return key


