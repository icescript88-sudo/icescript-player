def get_vault_key() -> bytes:
    """Retrieve the AES-256 Course Vault Master Key.
    Key is assembled from fragments at runtime — never stored in plain text.
    """
    return _assemble(0x1A)


def get_signing_secret() -> bytes:
    """Retrieve the HMAC Signing Secret for offline license validation.
    Key is assembled from fragments at runtime — never stored in plain text.
    """
    return _assemble(0x2B)


def get_default_admin_credential() -> str:
    """Retrieve the default admin password.
    Derived from vault key hash — not stored as a literal string.
    """
    import os
    env_override = os.environ.get("ICESCRIPT_ADMIN_PASSWORD")
    if env_override:
        return env_override

    # Derive from vault key hash so it's not a string literal in the binary
    vk = get_vault_key()
    h = hashlib.sha256(b"admin-credential:" + vk).hexdigest()
    # Produce a human-readable default: "ices" + first 8 hex chars = "ices4dd04f92"
    return "ices" + h[:8]
