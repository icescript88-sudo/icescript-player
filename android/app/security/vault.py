"""
Secure Key Vault — Runtime key assembly with multi-layer obfuscation.

Keys are never stored in plain text. Instead:
  1. Each key is XOR-split into two random-looking parts (part + mask)
  2. Parts are base85-encoded to look like random data
  3. Keys are assembled only on demand and verified via SHA-256 checksum
  4. Anti-tampering detection rejects modified binaries
  5. Assembled keys are NOT cached — reconstructed each call

This module should be compiled to .pyd via Cython for production builds.
"""
